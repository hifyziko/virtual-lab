const fs=require('fs'),path=require('path');
const dir=path.join(__dirname,'synchronous');
let html=fs.readFileSync(path.join(dir,'princip-template.html'),'utf8');
const ref=fs.readFileSync(path.join(__dirname,'../HiFyziko_TR04_pricna_vetev_v8.html'),'utf8');
const mathCss=ref.match(/<style id="katex-typesetting">([\s\S]*?)<\/style>/)[1];
const lib=[...ref.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].find(m=>m[1].trim().startsWith('!function')&&m[1].includes('ParseError'))[1];
html=html.replace('</head>',()=>'<style>'+mathCss+'</style><script>'+lib+'</script></head>');
if(!fs.existsSync(path.join(dir,'field-basis.js')))require('./synchronous/build-fields.cjs');
for(const [tag,file] of [['STYLE','princip.css'],['MODEL','princip-model.js'],['GEOMETRY','ipm-geometry.js'],['BASIS','field-basis.js'],['CONTOURS','../magnetic-field/contours.js'],['FIELD','field-lines.js'],['ART','machine-art.js'],['CHARTS','charts.js'],['TYPESETTING','math-typesetting.js'],['UI','princip.js']])html=html.replace('/*'+tag+'*/',()=>fs.readFileSync(path.join(dir,file),'utf8'));
fs.writeFileSync(path.join(dir,'princip.html'),html);
console.log('Built synchronous principle');
